const assert=require('node:assert/strict');
const {sauronView}=require('../map-model.js');
const now=1794050000000;
const rumor=sauronView(null,now);
assert.equal(rumor.visible,true);
assert.equal(rumor.mode,'rumor');
assert.match(rumor.detail,/nem Sauron valódi/);
assert.deepEqual(sauronView({game:null},now),rumor,'Logging in must not remove the pre-game sighting.');
assert.deepEqual(sauronView(null,now+1000),rumor,'Sighting must be shared for its two-hour slot.');
const game={id:'game',status:'preparation',city_name:'Prága',city_lat:50,city_lng:14,config:{route:[[50.1,14.1],[50.2,14.2]]}};
assert.equal(sauronView({game},now).mode,'rumor','Prepared games still show the other-continent sighting.');
assert.notDeepEqual(sauronView(null,now+7200000).position,rumor.position,'Sighting must move every two hours.');
assert(rumor.city.includes('Ázsia')||rumor.city.includes('Ausztrália')||rumor.city.includes('Amerika')||rumor.city.includes('Afrika'));
assert.equal(rumor.nextChange%7200000,0);
game.status='active';game.started_at=new Date(now-3600000).toISOString();
assert.deepEqual(sauronView({game,sauron:[50.15,14.15]},now).position,[50.15,14.15]);
assert.equal(sauronView({game,sauron:null},now).visible,false,'Must not replace server-hidden Sauron with a fabricated position.');
assert.equal(sauronView({game,sauron:null},now).position,null);
console.log('PASS: pre-game visibility, login continuity, shared rumor, preparation, live position, cooldown hiding');
