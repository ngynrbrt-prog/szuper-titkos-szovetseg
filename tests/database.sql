-- Runs against hosted staging/production inside one rollback-only transaction.
begin;
create temporary table checks(name text, passed boolean);
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); sa uuid:=gen_random_uuid(); sb uuid:=gen_random_uuid();
 pa uuid; pb uuid; inv text:=encode(extensions.gen_random_bytes(24),'hex'); out jsonb; item uuid; gem uuid; gid uuid; rejected bool;
 pts jsonb:='[[50.0875,14.4213],[50.0876,14.4213],[50.0877,14.4213],[50.0878,14.4213],[50.0879,14.4213],[50.0880,14.4213]]';
begin
 insert into auth.users(id,email) values(a,a||'@test.invalid'),(b,b||'@test.invalid');
 insert into auth.sessions(id,user_id) values(sa,a),(sb,b);
 insert into game_private.invites(token_hash,is_admin) values(encode(extensions.digest(inv,'sha256'),'hex'),true);
 pa:=public.game_register_invited('AuditAdmin','12345678',a,inv,'{}');
 insert into checks values('admin invite', (select is_admin from public.players where id=pa));
 rejected:=false;begin perform public.game_register_invited('AuditDuplicate','12345678',b,inv,'{}');exception when others then rejected:=true;end;
 insert into checks values('one-use invite',rejected);
 insert into game_private.invites(token_hash) values(encode(extensions.digest('second-test-invite','sha256'),'hex'));
 pb:=public.game_register_invited('AuditPlayer','87654321',b,'second-test-invite','{}');
 insert into checks values('correct PIN',public.game_verify_player('auditplayer','87654321')=b);
 for item in select gen_random_uuid() from generate_series(1,5) loop perform public.game_verify_player('AuditPlayer','00000000'); end loop;
 insert into checks values('lock after five wrong PINs',public.game_verify_player('AuditPlayer','87654321') is null);
 update game_private.player_credentials set locked_until=null where player_id=pb;
 rejected:=false;begin perform public.game_action(b,'invite','{}',sb);exception when others then rejected:=true;end;
 insert into checks values('player cannot invite',rejected);
 rejected:=false;begin perform public.game_action(a,'state','{}',null);exception when others then rejected:=true;end;
 insert into checks values('missing/revoked session blocked',rejected);
 out:=public.game_action(a,'create',jsonb_build_object('city','Audit Prague','lat',50.0875,'lng',14.4213,'mordor',jsonb_build_array(50.0875,14.4213),'points',pts,'route',pts,'safe',true),sa);
 gid:=(out->'game'->>'id')::uuid;
 insert into checks values('six rings and forty gems',(select count(*)=6 from public.items where game_id=gid and item_type='ring') and (select count(*)=40 from public.items where game_id=gid and item_type='gem'));
 out:=public.game_action(a,'start','{}',sa);
 out:=public.game_action(a,'location','{"lat":50.0875,"lng":14.4213,"accuracy":5}',sa);
 out:=public.game_action(b,'location','{"lat":50.0875,"lng":14.4213,"accuracy":5}',sb);
 select id into item from public.items where game_id=gid and item_type='ring' order by latitude,id limit 1;
 out:=public.game_action(a,'pickup',jsonb_build_object('item',item),sa);
 rejected:=false;begin perform public.game_action(b,'pickup',jsonb_build_object('item',item),sb);exception when others then rejected:=true;end;
 insert into checks values('duplicate pickup blocked',rejected);
 out:=public.game_action(b,'rob',jsonb_build_object('item',item),sb);
 insert into checks values('robbery transfers ownership',(select owner_id=pb from public.items where id=item));
 rejected:=false;begin perform public.game_action(a,'rob',jsonb_build_object('item',item),sa);exception when others then rejected:=true;end;
 insert into checks values('robbery cooldown',rejected);
 out:=public.game_action(b,'destroy',jsonb_build_object('item',item),sb);
 insert into checks values('Mordor destruction and score',(select status='destroyed' and owner_id is null from public.items where id=item) and (select rings_destroyed=1 and sestertius_earned=1000 from public.game_results where game_id=gid and player_id=pb));
 select id into gem from public.items where game_id=gid and item_type='gem' limit 1;
 update public.player_locations set latitude=50.09 where player_id=pa;
 rejected:=false;begin perform public.game_action(a,'pickup',jsonb_build_object('item',gem),sa);exception when others then rejected:=true;end;
 insert into checks values('remote pickup blocked',rejected);
 update public.player_locations set latitude=50.0875,updated_at=now()-interval '31 seconds' where player_id=pa;
 rejected:=false;begin perform public.game_action(a,'pickup',jsonb_build_object('item',gem),sa);exception when others then rejected:=true;end;
 insert into checks values('stale GPS blocked',rejected);
 out:=public.game_action(a,'stop','{}',sa);
 out:=public.game_action(b,'state','{}',sb);
 insert into checks values('stopped location hidden',not exists(select 1 from jsonb_array_elements(out->'locations') l where l->>'player_id'=pa::text));
 out:=public.game_action(a,'location','{"lat":50.0875,"lng":14.4213,"accuracy":5}',sa);
 select id into item from public.items where game_id=gid and item_type='ring' and status='ground' order by latitude,id limit 1;
 out:=public.game_action(a,'pickup',jsonb_build_object('item',item),sa);
 update public.games set started_at=now()-interval '30 minutes 1 second' where id=gid;
 update public.player_locations set active_seconds=901 where player_id=pa;
 out:=public.game_action(a,'state','{}',sa);
 insert into checks values('Sauron captures after immunity',(select status='sauron' from public.items where id=item));
 out:=public.game_action(a,'recover',jsonb_build_object('item',item),sa);
 insert into checks values('ring recovery',(select owner_id=pa and status='owned' from public.items where id=item));
 out:=public.game_action(a,'finish','{}',sa);
 insert into checks values('finish stores winner',(out->'game'->>'status'='finished') and out->'game'->>'winner_id' is not null);
 insert into checks values('anonymous table denied',not has_table_privilege('anon','public.players','SELECT'));
 insert into checks values('authenticated direct game RPC denied',not has_function_privilege('authenticated','public.game_action(uuid,text,jsonb,uuid)','EXECUTE'));
end $$;
select * from checks;
rollback;
